#!/usr/bin/env python3
"""Eww audio device routing, notification history and do not disturb."""

import fcntl
import hashlib
import html
import json
import os
from pathlib import Path
import subprocess
import sys

import afk
from theme import atomic

DND_RULE = "do-not-disturb"


def capture(args):
    return subprocess.run(args, capture_output=True, text=True, check=True, timeout=5).stdout.strip()


def notify(title, body="", critical=False):
    capture(["notify-send", "-a", "Desktop", "-u", "critical" if critical else "normal",
             title, html.escape(body)])


def audio_devices():
    sinks = json.loads(capture(["pactl", "-f", "json", "list", "sinks"]))
    sources = json.loads(capture(["pactl", "-f", "json", "list", "sources"]))
    return sinks, [source for source in sources if not source["name"].endswith(".monitor")
                   and source.get("properties", {}).get("device.class") != "monitor"]


def switch_audio(kind, index):
    if kind not in ("output", "input"):
        raise ValueError("Unknown audio device type.")
    sinks, sources = audio_devices()
    devices = sinks if kind == "output" else sources
    device = next((item for item in devices if item["index"] == index), None)
    if device is None:
        raise RuntimeError("Audio device disconnected. Open the device list again.")
    suffix = "sink" if kind == "output" else "source"
    capture(["pactl", f"set-default-{suffix}", device["name"]])
    stream_type = "sink-inputs" if kind == "output" else "source-outputs"
    streams = json.loads(capture(["pactl", "-f", "json", "list", stream_type]))
    real_sources = {item["index"] for item in sources}
    for stream in streams:
        # Preserve desktop-audio recordings when switching the microphone.
        if kind == "input" and stream.get("source") not in real_sources:
            continue
        try:
            capture(["pactl", f"move-{stream_type[:-1]}", str(stream["index"]), device["name"]])
        except subprocess.CalledProcessError:
            remaining = json.loads(capture(["pactl", "-f", "json", "list", stream_type]))
            if any(item["index"] == stream["index"] for item in remaining):
                raise RuntimeError("Default device changed, but an active audio stream could not move.")


def notice_value(item, key):
    field = item.get(key, "")
    return str(field.get("data", "") if isinstance(field, dict) else field)


def history():
    data = json.loads(capture(["dunstctl", "history"]))
    items = data.get("data", [[]])[0]
    try:
        remember_apps([(notice_value(item, "appname"), notice_value(item, "icon_path")) for item in items])
    except (OSError, ValueError):
        pass  # App metadata must not prevent reading or clearing notification history.
    result = []
    for item in reversed(items):
        result.append({"summary": notice_value(item, "summary"), "body": notice_value(item, "body"),
                       "app": notice_value(item, "appname")})
    return result[:30]


def apps_path():
    return Path(os.environ.get("XDG_STATE_HOME", str(Path.home() / ".local/state"))) / "thomas-desktop/notification-apps.json"


def app_id(name):
    return hashlib.sha256(name.encode()).hexdigest()


def load_apps():
    path = apps_path()
    apps = json.loads(path.read_text()) if path.exists() else {}
    if not isinstance(apps, dict) or any(
            not isinstance(app, dict) or set(app) != {"name", "icon", "allowed"}
            or not isinstance(app["name"], str) or not app["name"].strip()
            or any(ord(char) < 32 or ord(char) == 127 for char in app["name"])
            or key != app_id(app["name"]) or not isinstance(app["icon"], str)
            or type(app["allowed"]) is not bool for key, app in apps.items()):
        raise ValueError("Invalid notification app settings; saved choices were left intact.")
    return apps


def remember_apps(items):
    with (afk.directory() / "dnd.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        apps = load_apps()
        before = json.dumps(apps)
        for name, icon in items:
            if not isinstance(name, str) or not name.strip() or any(ord(char) < 32 or ord(char) == 127 for char in name):
                continue
            key = app_id(name)
            app = apps.setdefault(key, {"name": name, "icon": "", "allowed": False})
            if isinstance(icon, str) and Path(icon).is_absolute() and Path(icon).is_file():
                app["icon"] = icon
        if json.dumps(apps) != before:
            atomic(apps_path(), (json.dumps(apps, ensure_ascii=False) + "\n").encode())


def dnd_config(apps, enabled):
    lines = ["# Private Eww notification settings; regenerated by desktop-controls.py.",
             f"[{DND_RULE}]", f"enabled = {str(enabled).lower()}"]
    for key, app in sorted(apps.items()):
        if app["allowed"]:
            # Dunst keeps backslashes; escape glob syntax once, then quote the INI value.
            pattern = "".join("\\" + char if char in '\\*?[]"' else char for char in app["name"])
            lines += [f"[{DND_RULE}-allow-{key}]", f"enabled = {str(enabled).lower()}",
                      f'appname = "{pattern}"', "skip_display = false"]
    return ("\n".join(lines) + "\n").encode()


def dnd_enabled():
    data = json.loads(capture(["dunstctl", "rules", "--json"]))
    for rule in data["data"][0]:
        if rule["name"]["data"] == DND_RULE:
            enabled = rule["enabled"]["data"]
            if type(enabled) is bool:
                return enabled
            break
    raise ValueError("Do not disturb unavailable. Reload Dunst notification rules.")


def watch_dnd():
    from gi.repository import Gio, GLib

    bus = Gio.bus_get_sync(Gio.BusType.SESSION, None)
    name = "org.freedesktop.Notifications"
    path = "/org/freedesktop/Notifications"
    interface = "org.dunstproject.cmd0"
    previous = None

    def refresh(*_):
        nonlocal previous
        text = ""
        try:
            reply = bus.call_sync(name, path, interface, "RuleList", None,
                                  GLib.VariantType.new("(aa{sv})"), Gio.DBusCallFlags.NO_AUTO_START, 3000, None)
            if any(rule.get("name") == DND_RULE and rule.get("enabled") is True for rule in reply.unpack()[0]):
                text = ""
        except GLib.Error:
            pass
        if text != previous:
            print(text, flush=True)
            previous = text
        return False

    def rule_changed(_connection, message, incoming, _data):
        if (incoming and message.get_message_type() == Gio.DBusMessageType.METHOD_CALL
                and message.get_interface() == interface and message.get_member() == "RuleEnable"
                and message.get_path() == path and message.get_body().unpack()[0] == DND_RULE):
            GLib.idle_add(refresh)
            return None  # An observed call belongs to Dunst; never dispatch or reply to it here.
        return message

    bus.add_filter(rule_changed, None)
    # RuleEnable has no change signal; observe only this rule's control calls.
    match = (f"type='method_call',destination='{name}',path='{path}',interface='{interface}',"
             f"member='RuleEnable',arg0='{DND_RULE}',eavesdrop='true'")
    bus.call_sync("org.freedesktop.DBus", "/org/freedesktop/DBus", "org.freedesktop.DBus", "AddMatch",
                  GLib.Variant("(s)", (match,)), None, Gio.DBusCallFlags.NONE, 3000, None)
    bus.signal_subscribe(name, interface, "ConfigReloaded", path, None, Gio.DBusSignalFlags.NONE, refresh)
    Gio.bus_watch_name_on_connection(bus, name, Gio.BusNameWatcherFlags.NONE, refresh, refresh)
    refresh()
    GLib.MainLoop().run()


def configure_dnd(toggle=False, key=None, initialize=False):
    # Serialize changes and load all rules together so DND never briefly switches off.
    with (afk.directory() / "dnd.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        try:
            previous = dnd_enabled()
        except ValueError:
            if not initialize:
                raise
            previous = False
        enabled = not previous if toggle else previous
        pause_level = int(capture(["dunstctl", "get-pause-level"]))
        if not 0 <= pause_level <= 100:
            raise ValueError("Invalid Dunst pause level.")
        try:
            saved = load_apps()
        except (OSError, ValueError):
            if not toggle or enabled:
                raise
            saved = {}  # Turning DND off must still work if app settings are unreadable.
        apps = {item: dict(app) for item, app in saved.items()}
        allowed_rules = [f"{DND_RULE}-allow-{item}" for item, app in apps.items() if app["allowed"]]
        rules = json.loads(capture(["dunstctl", "rules", "--json"]))["data"][0]
        names = {rule["name"]["data"] for rule in rules}
        if not enabled:
            allowed_rules = [name for name in names if name.startswith(f"{DND_RULE}-allow-")]
        if toggle and (not enabled or set(allowed_rules) <= names):
            action = "enable" if enabled else "disable"
            capture(["dunstctl", "rule", DND_RULE, action])
            for name in allowed_rules:
                if name in names:
                    capture(["dunstctl", "rule", name, action])
            if enabled:
                capture(["dunstctl", "close-all"])
            return
        # Dunst reload unconditionally unpauses; defer rule edits while another pause is active.
        if pause_level:
            raise RuntimeError("Notifications are paused. Resume them before changing app exceptions.")
        if key is not None:
            if key not in apps:
                raise ValueError("Notification app no longer available. Reopen Allowed apps.")
            apps[key]["allowed"] = not apps[key]["allowed"]
        base = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))) / "dunst/dunstrc"
        path = afk.directory() / "dunst-apps.conf"
        if not base.is_file() or any("," in str(item) for item in (base, path)):
            raise ValueError("Dunst configuration unavailable or its path contains a comma.")
        command = ["dunstctl", "reload", str(base), str(path)]
        atomic(path, dnd_config(apps, enabled))
        try:
            capture(command)
            if dnd_enabled() != enabled:
                raise RuntimeError("Dunst did not apply do not disturb settings.")
            if enabled:
                capture(["dunstctl", "close-all"])
            if key is not None:
                atomic(apps_path(), (json.dumps(apps, ensure_ascii=False) + "\n").encode())
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError):
            atomic(path, dnd_config(saved, previous))
            try:
                capture(command)
            except (OSError, subprocess.SubprocessError):
                pass
            raise


def pick_app():
    apps = sorted(load_apps().items(), key=lambda item: item[1]["name"].casefold())
    rows = [f"{'☑' if app['allowed'] else '☐'}  {app['name']}" for _, app in apps]
    result = subprocess.run(["rofi", "-dmenu", "-i", "-p", "Allowed apps", "-format", "i",
                             "-mesg", "Selected apps can interrupt Do not disturb"],
                            input="\n".join(rows), text=True, capture_output=True, check=False)
    if result.returncode == 0:
        index = int(result.stdout.strip())
        if not 0 <= index < len(apps):
            raise ValueError("Choose an app from the list.")
        configure_dnd(key=apps[index][0])
    elif result.returncode != 1:
        raise RuntimeError("App search could not open.")


def status():
    result = {"outputs": [], "inputs": [], "audio_available": False, "audio_error": "Audio unavailable",
              "afk": afk.active(), "dnd": False, "dnd_available": False,
              "apps": [], "apps_available": False, "apps_editable": False, "apps_error": "App list unavailable",
              "allowed_count": 0, "notifications": [], "history_available": False}
    try:
        sinks, sources = audio_devices()
        for key, devices, default_command in (("outputs", sinks, "get-default-sink"),
                                               ("inputs", sources, "get-default-source")):
            default = capture(["pactl", default_command])
            result[key] = [{"id": int(device["index"]), "name": device.get("description") or device["name"],
                            "selected": device["name"] == default} for device in devices]
        result.update(audio_available=True, audio_error="")
    except (OSError, ValueError, KeyError, subprocess.SubprocessError):
        pass
    try:
        result["dnd"] = dnd_enabled()
        result["dnd_available"] = True
        result["apps_editable"] = int(capture(["dunstctl", "get-pause-level"])) == 0
    except (OSError, ValueError, KeyError, IndexError, TypeError, subprocess.SubprocessError):
        pass
    try:
        result["notifications"] = history()
        result["history_available"] = True
    except (OSError, ValueError, IndexError, TypeError, subprocess.SubprocessError):
        pass
    try:
        apps = load_apps()
        result["apps"] = [dict(app, id=key, icons=[app["icon"]] if Path(app["icon"]).is_file() else [])
                          for key, app in sorted(apps.items(), key=lambda item: item[1]["name"].casefold())]
        result.update(apps_available=True, apps_error="", allowed_count=sum(app["allowed"] for app in apps.values()))
    except (OSError, ValueError) as error:
        result["apps_error"] = str(error)
    return result


def main(args):
    action = args[0] if args else "status"
    if action == "status":
        print(json.dumps(status()))
    elif action == "audio" and len(args) == 3:
        switch_audio(args[1], int(args[2]))
    elif action == "clear-history":
        history()
        capture(["dunstctl", "history-clear"])
    elif action == "dnd" and len(args) == 1:
        configure_dnd(toggle=True)
    elif action == "allow-app" and len(args) == 2:
        configure_dnd(key=args[1])
    elif action == "reload-dnd" and len(args) == 1:
        configure_dnd(initialize=True)
    elif action == "record-app" and len(args) == 1:
        remember_apps([(os.environ.get("DUNST_APP_NAME", ""), os.environ.get("DUNST_ICON_PATH", ""))])
    elif action == "pick-app" and len(args) == 1:
        pick_app()
    elif action == "watch-dnd" and len(args) == 1:
        watch_dnd()
    else:
        raise ValueError("Unknown desktop control.")


if __name__ == "__main__":
    try:
        main(sys.argv[1:])
    except BrokenPipeError:
        sys.exit(0)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(str(error), file=sys.stderr)
        if sys.argv[1:] == ["record-app"]:
            sys.exit(1)
        try:
            notify("Desktop control failed", str(error), critical=True)
        except (OSError, subprocess.SubprocessError):
            pass
        sys.exit(1)
